import OpenAI from 'openai';
import { RemedyImageCache } from '../model/remedyImageCache.model.js';
import { uploadOnCloudinary } from './commonMethod.js';

const IMAGE_MODEL = process.env.REMEDY_IMAGE_MODEL || 'gpt-image-1';
const IMAGE_SIZE = process.env.REMEDY_IMAGE_SIZE || '1024x1024';
const IMAGE_CACHE_ENABLED = process.env.REMEDY_IMAGE_CACHE_ENABLED !== 'false';
const OPENAI_API_KEY = process.env.OPENAI_API_KEY;
const DEFAULT_PER_IMAGE_TIMEOUT_MS = Number(
  process.env.REMEDY_IMAGE_PER_IMAGE_TIMEOUT_MS || 8000
);

let openai = null;

function getOpenAIClient() {
  if (!OPENAI_API_KEY) return null;
  if (!openai) {
    openai = new OpenAI({ apiKey: OPENAI_API_KEY });
  }
  return openai;
}

function toText(value) {
  return typeof value === 'string' ? value.trim() : '';
}

function normalizeKey(value) {
  return toText(value)
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function slugify(value) {
  return normalizeKey(value).replace(/\s+/g, '-').slice(0, 80) || 'remedy';
}

function buildPrompt(remedy) {
  const name = toText(remedy?.name) || 'Natural Remedy';
  const dosage = Array.isArray(remedy?.tags) && remedy.tags.length
    ? toText(remedy.tags[0])
    : '';
  const notes = toText(remedy?.notes);

  return [
    'Create a realistic, clean food-photography style image of this natural home remedy.',
    `Remedy name: ${name}.`,
    dosage ? `Dose context: ${dosage}.` : '',
    notes ? `Context: ${notes}.` : '',
    'Show only the drink/ingredients relevant to this remedy.',
    'No text, no labels, no watermark, no logo, no people.',
    'Bright natural lighting, neutral kitchen background, appetizing composition, square frame.',
  ]
    .filter(Boolean)
    .join(' ');
}

function buildRemedyKey(remedy) {
  const name = toText(remedy?.name);
  const firstTag = Array.isArray(remedy?.tags) ? toText(remedy.tags[0] || '') : '';
  return normalizeKey(`${name}|${firstTag}`);
}

function withTimeout(promise, ms, label = 'operation') {
  let timeoutId;
  const timeoutPromise = new Promise((_, reject) => {
    timeoutId = setTimeout(
      () => reject(new Error(`${label} timed out after ${ms}ms`)),
      ms
    );
  });

  return Promise.race([promise, timeoutPromise]).finally(() => {
    clearTimeout(timeoutId);
  });
}

async function generateImageBuffer(prompt) {
  const client = getOpenAIClient();
  if (!client) {
    throw new Error('OPENAI_API_KEY is missing for remedy image generation.');
  }

  const response = await client.images.generate({
    model: IMAGE_MODEL,
    prompt,
    size: IMAGE_SIZE,
  });

  const b64 = response?.data?.[0]?.b64_json;
  if (!b64) {
    throw new Error('Image generation returned empty data.');
  }

  return Buffer.from(b64, 'base64');
}

async function uploadGeneratedImage(imageBuffer, remedyName) {
  const publicId = `remedy-${slugify(remedyName)}-${Date.now()}`;
  const result = await uploadOnCloudinary(imageBuffer, {
    folder: 'grandmasante/remedies',
    resource_type: 'image',
    public_id: publicId,
    overwrite: false,
  });

  return {
    publicId: result.public_id,
    url: result.secure_url,
    thumbnailUrl: result.secure_url,
    source: 'ai-generated',
    sourcePage: '',
    license: 'Generated by Grandma Sante AI',
    licenseUrl: '',
    creator: 'Grandma Sante AI',
    creatorUrl: '',
    attribution: 'AI-generated remedy image',
  };
}

async function getCachedImage(remedyKey) {
  if (!IMAGE_CACHE_ENABLED) return null;
  const cache = await RemedyImageCache.findOne({ remedyKey }).lean();
  return cache?.image || null;
}

async function setCachedImage({ remedyKey, remedyName, prompt, image }) {
  if (!IMAGE_CACHE_ENABLED) return;

  await RemedyImageCache.findOneAndUpdate(
    { remedyKey },
    {
      remedyKey,
      remedyName,
      prompt,
      image,
      model: IMAGE_MODEL,
    },
    { upsert: true, new: true, setDefaultsOnInsert: true }
  );
}

async function getOrCreateImage(remedy) {
  const remedyKey = buildRemedyKey(remedy);
  if (!remedyKey) return null;

  const cachedImage = await getCachedImage(remedyKey);
  if (cachedImage?.url) return cachedImage;

  const prompt = buildPrompt(remedy);
  const imageBuffer = await generateImageBuffer(prompt);
  const image = await uploadGeneratedImage(imageBuffer, remedy?.name);

  await setCachedImage({
    remedyKey,
    remedyName: toText(remedy?.name) || 'Natural Remedy',
    prompt,
    image,
  });

  return image;
}

export async function enrichNaturalRemediesWithImages(
  remedies,
  {
    generateIfMissing = true,
    maxGenerateCount = 1,
    perImageTimeoutMs = DEFAULT_PER_IMAGE_TIMEOUT_MS,
  } = {}
) {
  if (!Array.isArray(remedies) || remedies.length === 0) return [];

  const enriched = [];
  let generatedCount = 0;

  for (const remedy of remedies) {
    const remedyKey = buildRemedyKey(remedy);
    const cachedImage = remedyKey ? await getCachedImage(remedyKey) : null;
    if (cachedImage?.url) {
      enriched.push({ ...remedy, image: cachedImage });
      continue;
    }

    const canGenerate = generateIfMissing && generatedCount < maxGenerateCount;
    if (!canGenerate) {
      enriched.push(remedy);
      continue;
    }

    try {
      generatedCount += 1;
      const image = await withTimeout(
        getOrCreateImage(remedy),
        perImageTimeoutMs,
        `remedy image generation (${toText(remedy?.name) || 'Unknown'})`
      );
      enriched.push(image ? { ...remedy, image } : remedy);
    } catch (error) {
      console.error(
        `[RemedyImage] Failed for "${toText(remedy?.name) || 'Unknown'}":`,
        error?.message || error
      );
      enriched.push(remedy);
    }
  }

  return enriched;
}

export async function warmupRemedyImages(remedies) {
  if (!Array.isArray(remedies) || remedies.length === 0) return;

  await Promise.allSettled(
    remedies.map(async (remedy) => {
      try {
        await getOrCreateImage(remedy);
      } catch (error) {
        console.error(
          `[RemedyImage][Warmup] Failed for "${toText(remedy?.name) || 'Unknown'}":`,
          error?.message || error
        );
      }
    })
  );
}
