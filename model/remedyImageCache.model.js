import mongoose from "mongoose";

const remedyImageCacheSchema = new mongoose.Schema(
  {
    remedyKey: { type: String, required: true, unique: true, index: true },
    remedyName: { type: String, required: true },
    prompt: { type: String, required: true },
    image: {
      publicId: { type: String },
      url: { type: String, required: true },
      thumbnailUrl: { type: String },
      source: { type: String, default: "ai-generated" },
      sourcePage: { type: String, default: "" },
      license: { type: String, default: "Generated by Grandma Sante AI" },
      licenseUrl: { type: String, default: "" },
      creator: { type: String, default: "Grandma Sante AI" },
      creatorUrl: { type: String, default: "" },
      attribution: { type: String, default: "AI-generated remedy image" },
    },
    model: { type: String, default: "gpt-image-1" },
  },
  { timestamps: true }
);

export const RemedyImageCache = mongoose.model(
  "RemedyImageCache",
  remedyImageCacheSchema
);
